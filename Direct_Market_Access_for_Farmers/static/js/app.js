function changeLanguage(lang) {
  if (!translations[lang] && lang !== 'ta') lang = 'en';
  localStorage.setItem('preferred_language', lang);

  // 1. Translate elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerText = translations[lang][key];
      }
    } else if (translations['en'][key] && lang === 'en') {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations['en'][key];
      } else {
        el.innerText = translations['en'][key];
      }
    }
  });

  // 2. Translate Categories (data-i18n-cat)
  const catElements = document.querySelectorAll('[data-i18n-cat]');
  catElements.forEach(el => {
    const cat = el.getAttribute('data-i18n-cat');
    if (categoryTranslations[cat] && categoryTranslations[cat][lang]) {
      el.innerText = categoryTranslations[cat][lang];
    } else if (categoryTranslations[cat] && categoryTranslations[cat]['en']) {
      el.innerText = categoryTranslations[cat]['en'];
    }
  });

  // 3. Translate Crop Names (data-i18n-crop)
  const cropElements = document.querySelectorAll('[data-i18n-crop]');
  cropElements.forEach(el => {
    const crop = el.getAttribute('data-i18n-crop');
    if (cropNameTranslations[crop] && cropNameTranslations[crop][lang]) {
      el.innerText = cropNameTranslations[crop][lang];
    } else if (cropNameTranslations[crop] && cropNameTranslations[crop]['en']) {
      el.innerText = cropNameTranslations[crop]['en'];
    }
  });

  // 4. Translate Descriptions (data-i18n-desc)
  const descElements = document.querySelectorAll('[data-i18n-desc]');
  descElements.forEach(el => {
    const desc = el.getAttribute('data-i18n-desc');
    if (cropDescTranslations[desc] && cropDescTranslations[desc][lang]) {
      el.innerText = cropDescTranslations[desc][lang];
    } else if (cropDescTranslations[desc] && cropDescTranslations[desc]['en']) {
      el.innerText = cropDescTranslations[desc]['en'];
    }
  });

  // 5. Translate Units (data-i18n-unit)
  const unitElements = document.querySelectorAll('[data-i18n-unit]');
  unitElements.forEach(el => {
    const unit = el.getAttribute('data-i18n-unit');
    if (unitTranslations[unit] && unitTranslations[unit][lang]) {
      el.innerText = unitTranslations[unit][lang];
    } else if (unitTranslations[unit] && unitTranslations[unit]['en']) {
      el.innerText = unitTranslations[unit]['en'];
    }
  });

  // Synchronize language dropdown select boxes
  const langSelects = document.querySelectorAll('.lang-select');
  langSelects.forEach(select => {
    select.value = lang;
  });
}

document.addEventListener('DOMContentLoaded', () => {
  // Initialize language from localStorage
  const savedLang = localStorage.getItem('preferred_language') || 'en';
  changeLanguage(savedLang);

  // Bind change listener to language selector
  const langSelects = document.querySelectorAll('.lang-select');
  langSelects.forEach(select => {
    select.addEventListener('change', (e) => {
      changeLanguage(e.target.value);
    });
  });

  // Price Total Calculator & Rangewise Delivery Calculation on produce detail page
  const qtyInput = document.getElementById('calc-quantity');
  const priceUnitElem = document.getElementById('unit-price');
  const deliveryRangeSelect = document.getElementById('delivery-range');
  const subtotalPriceElem = document.getElementById('calc-subtotal');
  const deliveryFeeElem = document.getElementById('calc-fee');
  const totalPriceElem = document.getElementById('calc-total');

  if (qtyInput && priceUnitElem && totalPriceElem) {
    const unitPrice = parseFloat(priceUnitElem.dataset.price || 0);

    const updateTotal = () => {
      const qty = parseFloat(qtyInput.value || 0);
      const subtotal = qty * unitPrice;
      
      let deliveryFee = 50.0;
      if (deliveryRangeSelect) {
        const selectedOpt = deliveryRangeSelect.options[deliveryRangeSelect.selectedIndex];
        deliveryFee = parseFloat(selectedOpt.dataset.fee || 50.0);
      }

      const total = subtotal + deliveryFee;

      if (subtotalPriceElem) subtotalPriceElem.innerText = `₹${subtotal.toFixed(2)}`;
      if (deliveryFeeElem) deliveryFeeElem.innerText = `₹${deliveryFee.toFixed(2)}`;
      totalPriceElem.innerText = `₹${total.toFixed(2)}`;
    };

    qtyInput.addEventListener('input', updateTotal);
    if (deliveryRangeSelect) deliveryRangeSelect.addEventListener('change', updateTotal);
    updateTotal();
  }

  // Auto-dismiss flash notifications after 5 seconds
  const flashMsgs = document.querySelectorAll('.flash-msg');
  flashMsgs.forEach(msg => {
    setTimeout(() => {
      msg.style.opacity = '0';
      msg.style.transform = 'translateY(-10px)';
      msg.style.transition = 'all 0.4s ease';
      setTimeout(() => msg.remove(), 400);
    }, 5000);
  });
});